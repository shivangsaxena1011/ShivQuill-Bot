/**
 * AI-text detector: a language model judges each sentence in context, blended with measurable
 * stylometric signals. Results follow the familiar four-way split used by mainstream detectors:
 * AI-generated, AI-generated & AI-refined, human-written & AI-refined, human-written.
 *
 * When the model is unavailable or its answer is unusable, the statistical signals alone are used
 * and the result is marked low-confidence. Scores are signals, never proof of authorship.
 */
import { z } from 'zod';
import { completeStructured, looseNumber, looseString } from './structuredCompletion.js';
import { isAbortError } from './requestAbort.js';
import { tokenize, sentenceSpans } from './plagiarism/text.js';

export type AiLabel = 'ai' | 'ai_refined' | 'human_refined' | 'human';

export interface AiSentenceResult {
  text: string;
  start: number;
  end: number;
  words: number;
  /** 0-100 likelihood that the sentence is machine-written */
  aiLikelihood: number;
  label: AiLabel;
  /** legacy 3-way flag kept for older clients */
  flag: 'human' | 'mixed' | 'ai';
  reason?: string;
}

export interface AiDetectionResult {
  aiPercentage: number;
  humanPercentage: number;
  breakdown: { aiGenerated: number; aiRefined: number; humanRefined: number; human: number };
  confidence: 'High' | 'Moderate' | 'Low';
  overallVerdict: 'Likely Human-Written' | 'Mixed Signals' | 'Likely AI-Generated';
  summary: string;
  sentences: AiSentenceResult[];
  explanations: Array<{ text: string; label: AiLabel; aiLikelihood: number; reason: string }>;
  signals: string[];
  metrics: {
    entropyScore: number;
    burstinessScore: number;
    shannonEntropy: number;
    sentenceLengthCV: number;
    typeTokenRatio: number;
    aiPhraseCount: number;
  };
  method: 'model+statistics' | 'statistics';
  methodNote: string;
  analyzedWords: number;
  totalWords: number;
  truncated: boolean;
  experimentalStatus: true;
  analyzerType: 'hybrid_llm_statistical' | 'statistical_heuristic';
  falsePositiveRisk: string;
  disclaimer: string;
}

export const MIN_WORDS = 40;
const MAX_WORDS = (() => {
  const n = parseInt(process.env.AI_DETECTOR_MAX_WORDS || '', 10);
  return Number.isFinite(n) && n >= 200 ? n : 6000;
})();

// Phrases language models overuse (weighted); matched case-insensitively on word boundaries
const STRONG_TELLS = [
  'delve', 'delves', 'delving', 'tapestry', 'testament to', 'in the realm of', 'navigate the complexities', 'navigating the complexities',
  'harness the power', 'unlock the potential', 'plays a pivotal role', 'pivotal role', 'plays a crucial role', 'plays a vital role',
  'shed light on', 'sheds light on', 'ever-evolving', 'ever-changing landscape', 'multifaceted', 'seamlessly', 'embark on', 'in today\'s fast-paced',
  'it is important to note', 'it is worth noting', 'it\'s important to note', 'in conclusion', 'in summary', 'a myriad of', 'myriad',
  'underscores the importance', 'fostering', 'holistic approach', 'paving the way', 'game-changer', 'cutting-edge', 'rich tapestry',
  'serves as a', 'a beacon of', 'intricate', 'nuanced understanding', 'resonate with', 'elevate your', 'dive into', 'unwavering'
];
const WEAK_TELLS = [
  'furthermore', 'moreover', 'additionally', 'consequently', 'notably', 'crucial', 'essential', 'significant', 'robust', 'comprehensive',
  'leverage', 'leveraging', 'utilize', 'utilizing', 'enhance', 'streamline', 'optimize', 'landscape', 'realm', 'paramount',
  'overall', 'ultimately', 'thus', 'therefore', 'various', 'diverse', 'innovative', 'transformative', 'dynamic', 'ensure'
];
const tellRe = (list: string[]) => new RegExp(`(?<![\\p{L}])(?:${list.map(p => p.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|')})(?![\\p{L}])`, 'giu');
const STRONG_RE = tellRe(STRONG_TELLS);
const WEAK_RE = tellRe(WEAK_TELLS);
const CONTRACTION_RE = /\b\w+(?:'|’)(?:t|s|re|ve|ll|d|m)\b/i;
const FIRST_PERSON_RE = /\b(?:i|me|my|mine|we|our|us)\b/i;
// Casual markers (not em dashes: language models use those a lot)
const CASUAL_RE = /(?:!{2,}|\?{2,}|\b(?:lol|gonna|wanna|kinda|yeah|ok|okay|btw|tbh|honestly|stuff)\b|\.\.\.|\()/i;

const SYSTEM_PROMPT = `You are an AI TEXT FORENSICS classifier. Decide, sentence by sentence, whether the text was written by a person or generated by a language model (ChatGPT, Claude, Gemini, Llama…).

Machine-written signs: generic statements without concrete specifics; even, polished rhythm; formulaic transitions (Furthermore, Moreover, In conclusion); stock phrases (delve, tapestry, pivotal, testament to, navigate the complexities); balanced "while X, Y" hedging; list-like structure; summarising restatements; no errors, no personal voice.
Human signs: concrete personal details, names, numbers, dates, anecdotes; idiosyncratic word choice or humour; uneven sentence lengths; small errors, fragments, asides; opinions with stakes; casual or domain-specific wording.

Labels per sentence:
- "ai": generated by AI
- "ai_refined": generated by AI and then lightly edited/refined
- "human_refined": written by a person, polished with an AI tool (grammar/paraphrase)
- "human": written by a person
"ai" is 0-100: likelihood that the sentence is machine-generated (consistent with the label: ai ≥ 70, ai_refined 55-69, human_refined 40-54, human < 40).

When unsure, lean towards human: false accusations are worse than misses. Judge each sentence in the context of the whole passage (AI text is usually AI throughout; a person's text can contain single generic sentences).

Return ONLY JSON:
{"summary":"one or two sentences on why the text reads as human or AI","sentences":[{"i":1,"label":"human","ai":12,"reason":"short reason (max 15 words)"}]}
Include every sentence number exactly once.`;

const llmSchema = z.object({
  summary: looseString(400),
  sentences: z
    .preprocess(v => (Array.isArray(v) ? v : []), z.array(z.unknown()))
    .transform(items =>
      items.flatMap(it => {
        const r = z
          .object({
            i: looseNumber(-1),
            label: z.preprocess(v => String(v ?? '').toLowerCase().replace(/[\s&-]+/g, '_'), z.string()),
            ai: looseNumber(-1),
            reason: looseString(160)
          })
          .safeParse(it);
        return r.success && r.data.i >= 1 ? [r.data] : [];
      })
    )
});

const clamp = (n: number, lo = 0, hi = 100) => Math.min(hi, Math.max(lo, n));

function labelFor(score: number): AiLabel {
  if (score >= 70) return 'ai';
  if (score >= 55) return 'ai_refined';
  if (score >= 40) return 'human_refined';
  return 'human';
}

const LABEL_SCORE: Record<AiLabel, number> = { ai: 85, ai_refined: 62, human_refined: 47, human: 15 };

interface Sent {
  text: string;
  start: number;
  end: number;
  words: number;
}

function splitSentences(text: string): Sent[] {
  const tokens = tokenize(text);
  const spans = sentenceSpans(text, tokens);
  const out: Sent[] = [];
  const MAX_SENTENCE_WORDS = 60;
  for (const s of spans) {
    const words = s.t1 - s.t0;
    // Text without punctuation would be one giant "sentence": cut it into ~40-word pieces so the
    // word cap, batching and per-sentence scores still work
    if (words > MAX_SENTENCE_WORDS) {
      for (let t = s.t0; t < s.t1; t += 40) {
        const t1 = Math.min(s.t1, t + 40);
        const start = tokens[t].start;
        const end = t1 === s.t1 ? s.end : tokens[t1 - 1].end;
        out.push({ text: text.slice(start, end), start, end, words: t1 - t });
      }
      continue;
    }
    // Include the closing punctuation/quotes in the sentence
    let end = s.end;
    while (end < text.length && /[.!?。！？।॥'"”’)\]]/.test(text[end])) end++;
    // Fold very short fragments ("Yes.", headings) into the previous sentence
    if (words < 3 && out.length) {
      const prev = out[out.length - 1];
      prev.end = end;
      prev.text = text.slice(prev.start, prev.end);
      prev.words += words;
      continue;
    }
    out.push({ text: text.slice(s.start, end), start: s.start, end, words });
  }
  return out;
}

function percentShares(counts: number[]): number[] {
  const total = counts.reduce((a, b) => a + b, 0);
  if (!total) return counts.map((_, i) => (i === counts.length - 1 ? 100 : 0));
  const exact = counts.map(c => (c / total) * 100);
  const out = exact.map(Math.floor);
  let rest = 100 - out.reduce((a, b) => a + b, 0);
  const order = exact.map((_, i) => i).sort((a, b) => exact[b] - out[b] - (exact[a] - out[a]));
  for (const i of order) {
    if (rest-- <= 0) break;
    out[i]++;
  }
  return out;
}

function documentStats(text: string, sents: Sent[]) {
  // Same tokenizer as everywhere else (splits Chinese/Japanese/Thai into words)
  const words = tokenize(text).map(t => t.w).filter(w => w.length >= 2 || /[^\p{Script=Latin}\p{N}]/u.test(w));
  const total = words.length || 1;
  const freq = new Map<string, number>();
  for (const w of words) freq.set(w, (freq.get(w) || 0) + 1);
  let entropy = 0;
  for (const c of freq.values()) {
    const p = c / total;
    entropy -= p * Math.log2(p);
  }
  // Moving-average TTR over 100-word windows (length-independent vocabulary variety)
  let ttr = freq.size / total;
  if (words.length > 120) {
    let sum = 0;
    let windows = 0;
    for (let i = 0; i + 100 <= words.length; i += 50) {
      sum += new Set(words.slice(i, i + 100)).size / 100;
      windows++;
    }
    ttr = sum / windows;
  }
  const lens = sents.map(s => s.words);
  const mean = lens.reduce((a, b) => a + b, 0) / (lens.length || 1);
  const sd = Math.sqrt(lens.reduce((a, b) => a + (b - mean) ** 2, 0) / (lens.length || 1));
  const cv = mean > 0 && lens.length > 1 ? sd / mean : 0;
  return { entropy, ttr, cv, mean };
}

function sentenceStatScore(s: Sent, doc: ReturnType<typeof documentStats>, nSent: number): { score: number; tells: string[] } {
  const strong = [...s.text.matchAll(STRONG_RE)].map(m => m[0].toLowerCase());
  const weak = [...s.text.matchAll(WEAK_RE)].map(m => m[0].toLowerCase());
  let score = 32;
  score += Math.min(2, strong.length) * 16;
  score += Math.min(3, weak.length) * 6;
  if (nSent >= 4 && doc.cv < 0.22 && s.words >= 12 && s.words <= 32) score += 10; // monotone rhythm
  if (nSent >= 4 && doc.cv > 0.6) score -= 10; // bursty, human-like rhythm
  if (CONTRACTION_RE.test(s.text)) score -= 8;
  if (FIRST_PERSON_RE.test(s.text)) score -= 6;
  if (CASUAL_RE.test(s.text)) score -= 8;
  if (/\d/.test(s.text)) score -= 4; // concrete figures/dates
  if (s.words < 6) score -= 6;
  return { score: clamp(Math.round(score), 3, 95), tells: [...new Set([...strong, ...weak])] };
}

interface Batch {
  from: number;
  to: number;
}

function batches(sents: Sent[], maxChars = 6000, maxSentences = 50): Batch[] {
  const out: Batch[] = [];
  let from = 0;
  let chars = 0;
  for (let i = 0; i < sents.length; i++) {
    chars += sents[i].text.length;
    if (i > from && (chars > maxChars || i - from >= maxSentences)) {
      out.push({ from, to: i });
      from = i;
      chars = sents[i].text.length;
    }
  }
  if (from < sents.length) out.push({ from, to: sents.length });
  return out;
}

export async function detectAiText(
  text: string,
  opts: { model?: string; signal?: AbortSignal; onStatus?: (m: string) => void } = {}
): Promise<AiDetectionResult> {
  const allSents = splitSentences(text);
  const totalWords = allSents.reduce((a, s) => a + s.words, 0);

  // Analyse up to MAX_WORDS (whole sentences)
  const sents: Sent[] = [];
  let analyzedWords = 0;
  for (const s of allSents) {
    if (analyzedWords + s.words > MAX_WORDS && sents.length) break;
    sents.push(s);
    analyzedWords += s.words;
  }
  const truncated = sents.length < allSents.length;
  const doc = documentStats(text.slice(0, sents.length ? sents[sents.length - 1].end : 0), sents);
  const stats = sents.map(s => sentenceStatScore(s, doc, sents.length));

  // ---- model judgement -------------------------------------------------------------------
  const llmScore: Array<number | null> = sents.map(() => null);
  const llmLabel: Array<AiLabel | null> = sents.map(() => null);
  const llmReason: string[] = sents.map(() => '');
  let summary = '';
  let modelFailures = 0;
  const plan = batches(sents);
  for (let b = 0; b < plan.length; b++) {
    const { from, to } = plan[b];
    opts.onStatus?.(plan.length > 1 ? `Analyzing part ${b + 1} of ${plan.length}…` : 'Analyzing writing patterns…');
    const numbered = sents.slice(from, to).map((s, k) => `[${k + 1}] ${s.text.replace(/\s+/g, ' ').trim()}`).join('\n');
    try {
      const parsed = await completeStructured(llmSchema, SYSTEM_PROMPT, `Classify these ${to - from} sentences:\n\n${numbered}`, opts.model, 0, opts.signal);
      if (!summary && parsed.summary) summary = parsed.summary;
      for (const r of parsed.sentences) {
        const idx = from + Math.round(r.i) - 1;
        if (idx < from || idx >= to) continue;
        const label = (['ai', 'ai_refined', 'human_refined', 'human'] as AiLabel[]).find(l => r.label === l) || null;
        const score = r.ai >= 0 && r.ai <= 100 ? r.ai : label ? LABEL_SCORE[label] : null;
        if (score === null) continue;
        llmScore[idx] = score;
        llmLabel[idx] = label;
        llmReason[idx] = r.reason;
      }
    } catch (err: any) {
      if (isAbortError(err) || opts.signal?.aborted) throw err;
      modelFailures++;
      console.warn('[ShivQuill AI Detector] Model judgement unavailable for a batch:', String(err?.message || err).slice(0, 200));
    }
  }
  const judged = llmScore.filter(s => s !== null).length;
  const modelUsed = judged >= Math.max(1, Math.ceil(sents.length * 0.6));

  // ---- combine ---------------------------------------------------------------------------
  const sentences: AiSentenceResult[] = sents.map((s, i) => {
    const st = stats[i].score;
    const m = llmScore[i];
    const score = Math.round(modelUsed && m !== null ? 0.72 * m + 0.28 * st : st);
    const label = labelFor(score);
    const tells = stats[i].tells;
    const reason =
      llmReason[i] ||
      (tells.length ? `Uses phrasing common in AI text: ${tells.slice(0, 3).map(t => `“${t}”`).join(', ')}` : label === 'human' ? 'Natural, varied phrasing' : 'Even, generic phrasing');
    return {
      text: s.text,
      start: s.start,
      end: s.end,
      words: s.words,
      aiLikelihood: score,
      label,
      flag: score >= 55 ? 'ai' : score >= 40 ? 'mixed' : 'human',
      reason
    };
  });

  const wordsBy = (labels: AiLabel[]) => sentences.filter(s => labels.includes(s.label)).reduce((a, s) => a + s.words, 0);
  // Largest-remainder rounding: the four shares always add up to exactly 100
  const [aiGen, aiRef, humRef, human] = percentShares([wordsBy(['ai']), wordsBy(['ai_refined']), wordsBy(['human_refined']), wordsBy(['human'])]);
  const aiPercentage = Math.min(100, aiGen + aiRef);

  const aiPhraseCount = stats.reduce((a, s) => a + s.tells.length, 0);
  const signals: string[] = [];
  if (sents.length >= 4) {
    if (doc.cv < 0.22) signals.push(`Very even sentence lengths (variation ${doc.cv.toFixed(2)}), typical of generated text`);
    else if (doc.cv > 0.6) signals.push(`Uneven, natural sentence rhythm (variation ${doc.cv.toFixed(2)})`);
  }
  if (aiPhraseCount >= 3) signals.push(`${aiPhraseCount} phrases that AI models overuse`);
  if (CONTRACTION_RE.test(text) || FIRST_PERSON_RE.test(text)) signals.push('Personal voice (contractions or first person) — more common in human writing');
  if (doc.ttr < 0.45 && analyzedWords > 120) signals.push('Repetitive vocabulary');

  const confidence: AiDetectionResult['confidence'] =
    !modelUsed || analyzedWords < 80 ? 'Low' : analyzedWords >= 250 && modelFailures === 0 ? 'High' : 'Moderate';

  const explanations = sentences
    .filter(s => s.label === 'ai' || s.label === 'ai_refined')
    .sort((a, b) => b.aiLikelihood - a.aiLikelihood)
    .slice(0, 5)
    .map(s => ({ text: s.text.length > 220 ? s.text.slice(0, 217) + '…' : s.text, label: s.label, aiLikelihood: s.aiLikelihood, reason: s.reason || '' }));

  return {
    aiPercentage,
    humanPercentage: 100 - aiPercentage,
    breakdown: { aiGenerated: aiGen, aiRefined: aiRef, humanRefined: humRef, human },
    confidence,
    overallVerdict: aiPercentage >= 60 ? 'Likely AI-Generated' : aiPercentage >= 25 ? 'Mixed Signals' : 'Likely Human-Written',
    summary:
      summary ||
      (aiPercentage >= 60
        ? 'Most of the text shows patterns typical of AI-generated writing.'
        : aiPercentage >= 25
          ? 'Parts of the text show AI-like patterns; other parts read as human.'
          : 'The text mostly reads as human-written.'),
    sentences,
    explanations,
    signals,
    metrics: {
      entropyScore: Math.round(Math.min(100, doc.entropy * 12)),
      burstinessScore: Math.round(Math.min(100, doc.cv * 100)),
      shannonEntropy: parseFloat(doc.entropy.toFixed(3)),
      sentenceLengthCV: parseFloat(doc.cv.toFixed(3)),
      typeTokenRatio: parseFloat(doc.ttr.toFixed(3)),
      aiPhraseCount
    },
    method: modelUsed ? 'model+statistics' : 'statistics',
    methodNote: modelUsed
      ? 'A language model judged each sentence in context, combined with measured writing statistics.'
      : 'The AI model was unavailable, so only writing statistics were used. Treat this result as a rough estimate.',
    analyzedWords,
    totalWords,
    truncated,
    experimentalStatus: true,
    analyzerType: modelUsed ? 'hybrid_llm_statistical' : 'statistical_heuristic',
    falsePositiveRisk:
      'Formal, technical, non-native or heavily edited human writing can be flagged as AI. Use this as one signal, never as proof.',
    disclaimer: 'AI detection is probabilistic. Never make academic or employment decisions on a detector score alone.'
  };
}
